// Writes src/sandbox/aws-services.ts, every AWS service's endpoints and signing names, from
// the AWS SDK's own data: botocore's endpoints.json and service definitions, as the AWS CLI
// ships them. Run it when a newer CLI knows more services:
//
//   node scripts/aws-services.ts /usr/local/aws-cli/v2/current/dist/awscli/botocore/data
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gunzipSync } from 'node:zlib';

interface Endpoint { hostname?: string; credentialScope?: { region?: string; service?: string }; deprecated?: boolean }
interface Service { defaults?: Endpoint; endpoints?: Record<string, Endpoint>; isRegionalized?: boolean; partitionEndpoint?: string }

const dir = process.argv[2];
if (!dir || !existsSync(join(dir, 'endpoints.json'))) throw new Error('usage: node scripts/aws-services.ts <botocore data directory, with endpoints.json>');
const aws = (JSON.parse(readFileSync(join(dir, 'endpoints.json'), 'utf8')) as { partitions: Array<{ partition: string; defaults: { hostname: string }; services: Record<string, Service> }> })
  .partitions.find((p) => p.partition === 'aws')!;

// Each service definition's endpoint prefix and signing name, from its latest version.
const signing = new Map<string, string>();
for (const name of readdirSync(dir).sort()) {
  if (!statSync(join(dir, name)).isDirectory()) continue;
  const latest = readdirSync(join(dir, name)).filter((v) => statSync(join(dir, name, v)).isDirectory()).sort().at(-1);
  if (!latest) continue;
  const file = join(dir, name, latest, 'service-2.json');
  const raw = existsSync(file) ? readFileSync(file) : existsSync(`${file}.gz`) ? gunzipSync(readFileSync(`${file}.gz`)) : undefined;
  if (!raw) continue;
  const { endpointPrefix, signingName } = (JSON.parse(raw.toString('utf8')) as { metadata: { endpointPrefix?: string; signingName?: string } }).metadata;
  if (endpointPrefix && !signing.has(endpointPrefix)) signing.set(endpointPrefix, signingName ?? endpointPrefix);
}

const DEFAULT = '{service}.{region}.{dnsSuffix}';
const regional: Array<[string, string, string?]> = [];
const global: Array<[string, string, string, string]> = [];
for (const prefix of [...new Set([...Object.keys(aws.services), ...signing.keys()])].sort()) {
  const service = aws.services[prefix] ?? {};
  const name = service.defaults?.credentialScope?.service ?? signing.get(prefix) ?? prefix;
  const partition = service.partitionEndpoint ? service.endpoints?.[service.partitionEndpoint] : undefined;
  if (partition?.hostname && !partition.deprecated) {
    global.push([prefix, partition.hostname, partition.credentialScope?.service ?? name, partition.credentialScope?.region ?? 'us-east-1']);
  }
  if (service.isRegionalized === false) continue;
  const template = service.defaults?.hostname ?? aws.defaults.hostname;
  if (!template.includes('{region}')) continue;
  regional.push(template === DEFAULT ? [prefix, name] : [prefix, name, template]);
}

const cli = /aws-cli\/v2\/([\d.]+)\//.exec(dir)?.[1];
const lines = [
  `// Generated by scripts/aws-services.ts from botocore's data${cli ? ` (AWS CLI ${cli})` : ''}: don't edit it by hand.`,
  '',
  '/** Every regional AWS service: its endpoint prefix, its signing name, and its host when not `{service}.{region}.{dnsSuffix}`. */',
  'export const REGIONAL_SERVICES: ReadonlyArray<readonly [string, string, string?]> = [',
  ...regional.map((entry) => `  ${JSON.stringify(entry).replaceAll('"', "'")},`),
  '];',
  '',
  '/** Every global AWS endpoint: the service, its host, its signing name, and the region it signs for. */',
  'export const GLOBAL_SERVICES: ReadonlyArray<readonly [string, string, string, string]> = [',
  ...global.map((entry) => `  ${JSON.stringify(entry).replaceAll('"', "'")},`),
  '];',
  '',
];
writeFileSync(new URL('../src/sandbox/aws-services.ts', import.meta.url), lines.join('\n'));
console.log(`${regional.length} regional services, ${global.length} global endpoints`);
